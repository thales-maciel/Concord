//! A fresh test process: the client must initialize TLS even without the built-in hub running.
//! Exercise both HTTPS and WSS with certificate verification, without Internet access.

use std::sync::Arc;
use std::time::Duration;

use futures_util::{SinkExt, StreamExt};
use rustls::pki_types::{CertificateDer, PrivatePkcs8KeyDer};
use tokio::io::{AsyncReadExt, AsyncWriteExt};
use tokio_rustls::TlsAcceptor;
use tokio_tungstenite::{connect_async_tls_with_config, tungstenite::Message, Connector};
use vox_client_core::HubClient;

const CA: &[u8] = include_bytes!("fixtures/tls-ca.der");
const CERT: &[u8] = include_bytes!("fixtures/tls-localhost.der");
// Public test-only key; generated by fixtures/generate-tls.sh, never used by the application.
const KEY: &[u8] = include_bytes!("fixtures/tls-localhost-key.der");

#[tokio::test]
async fn client_initializes_ring_for_verified_https_and_wss() {
    tokio::time::timeout(Duration::from_secs(15), async {
        assert!(rustls::crypto::CryptoProvider::get_default().is_none());
        let _hub = HubClient::new("https://localhost").unwrap();
        assert!(rustls::crypto::CryptoProvider::get_default().is_some());

        let server = rustls::ServerConfig::builder()
            .with_no_client_auth()
            .with_single_cert(
                vec![CertificateDer::from(CERT.to_vec())],
                PrivatePkcs8KeyDer::from(KEY.to_vec()).into(),
            )
            .unwrap();
        let acceptor = TlsAcceptor::from(Arc::new(server));
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let port = listener.local_addr().unwrap().port();
        let task = tokio::spawn(async move {
            let (tcp, _) = listener.accept().await.unwrap();
            let mut tls = acceptor.accept(tcp).await.unwrap();
            let mut request = Vec::new();
            while !request.ends_with(b"\r\n\r\n") {
                request.push(tls.read_u8().await.unwrap());
                assert!(request.len() < 8192);
            }
            tls.write_all(b"HTTP/1.1 200 OK\r\nContent-Length: 2\r\nConnection: close\r\n\r\nok")
                .await
                .unwrap();
            tls.shutdown().await.unwrap();

            let (tcp, _) = listener.accept().await.unwrap();
            let tls = acceptor.accept(tcp).await.unwrap();
            let mut ws = tokio_tungstenite::accept_async(tls).await.unwrap();
            let message = ws.next().await.unwrap().unwrap();
            ws.send(message).await.unwrap();
        });

        let mut roots = rustls::RootCertStore::empty();
        roots.add(CertificateDer::from(CA.to_vec())).unwrap();
        let client = rustls::ClientConfig::builder()
            .with_root_certificates(roots)
            .with_no_client_auth();
        // Explicit test trust avoids OS-specific certificate-lifetime policies. Verification
        // stays enabled; neither HTTP nor WebSocket accepts arbitrary/self-signed peers.
        let http = reqwest::Client::builder()
            .no_proxy()
            .tls_backend_preconfigured(client.clone())
            .build()
            .unwrap();
        let response = http
            .get(format!("https://localhost:{port}/"))
            .send()
            .await
            .unwrap();
        assert_eq!(response.text().await.unwrap(), "ok");

        let (mut ws, _) = connect_async_tls_with_config(
            format!("wss://localhost:{port}/"),
            None,
            false,
            Some(Connector::Rustls(Arc::new(client))),
        )
        .await
        .unwrap();
        ws.send(Message::Text("ring works".into())).await.unwrap();
        assert_eq!(
            ws.next().await.unwrap().unwrap(),
            Message::Text("ring works".into())
        );
        task.await.unwrap();
    })
    .await
    .expect("loopback HTTPS/WSS test timed out");
}
